/// Calculates the Two-Ray pathloss.
#[no_mangle]
pub extern "C" fn emane_rs_tworay_pathloss(
    d_distance: f64,
    d_local_alt: f64,
    d_remote_alt: f64,
) -> f64 {
    if d_distance == 0.0 {
        return 0.0;
    }

    let local_alt = if d_local_alt < 1.0 { 1.0 } else { d_local_alt };
    let remote_alt = if d_remote_alt < 1.0 {
        1.0
    } else {
        d_remote_alt
    };

    let pathloss = (40.0 * d_distance.log10()) - (20.0 * (local_alt.log10() + remote_alt.log10()));

    if pathloss < 0.0 {
        0.0
    } else {
        pathloss
    }
}

/// Calculates the FreeSpace pathloss for a single frequency.
#[no_mangle]
pub extern "C" fn emane_rs_freespace_pathloss_single(d_distance: f64, freq_hz: f64) -> f64 {
    const FSPL_CONST: f64 = 41.916_900_439_033_64;
    if d_distance == 0.0 {
        return 0.0;
    }
    let val = 20.0 * (FSPL_CONST * (freq_hz / 1000000.0) * (d_distance / 1000.0)).log10();
    if val < 0.0 {
        0.0
    } else {
        val
    }
}

/// Stateful Lognormal Fading Algorithm
use emane_plugin_api::random::{LegacyNormal, LegacyRandom};

#[repr(C)]
pub struct LognormalFadingParameters {
    pub dmu: f64,
    pub dsigma: f64,
    pub dlthresh: f64,
    pub maxpathloss: f64,
    pub duthresh: f64,
    pub minpathloss: f64,
    pub lmean: f64,
    pub lstddev: f64,
    pub counter: u32,
}

pub struct LognormalFadingState {
    param_counter: u32,
    reset: bool,
    depth_dbm: f64,
    nexttime_microsec: u64,
    rng: LegacyRandom,
    length_distribution: LegacyNormal,
    depth_distribution: LegacyNormal,
}

impl Default for LognormalFadingState {
    fn default() -> Self {
        Self::new()
    }
}

impl LognormalFadingState {
    pub fn new() -> Self {
        Self {
            param_counter: 0,
            reset: true,
            depth_dbm: 0.0,
            nexttime_microsec: 0,
            rng: LegacyRandom::seeded(5489),
            length_distribution: LegacyNormal::default(),
            depth_distribution: LegacyNormal::default(),
        }
    }

    pub fn process(
        &mut self,
        power_dbm: f64,
        params: &LognormalFadingParameters,
        now_microsec: u64,
    ) -> Option<f64> {
        if !power_dbm.is_finite()
            || !params.dmu.is_finite()
            || !params.dsigma.is_finite()
            || !params.lmean.is_finite()
            || !params.lstddev.is_finite()
            || params.lmean < 0.0
            || params.lstddev < 0.0
            || params.dlthresh > params.duthresh
            || params.minpathloss >= params.maxpathloss
        {
            return None;
        }

        if params.counter != self.param_counter {
            self.reset = true;
            self.param_counter = params.counter;
        }

        if self.reset || now_microsec >= self.nexttime_microsec {
            // Even a zero standard deviation consumes a draw and retains the
            // distribution's spare, just as the original std distributions do.
            let length_seconds =
                self.length_distribution
                    .sample(&mut self.rng, params.lmean, params.lstddev);
            let length_microseconds = (length_seconds * 1_000.0).trunc() as i64;
            self.nexttime_microsec =
                now_microsec.saturating_add_signed(length_microseconds.saturating_mul(1_000));
            let depth_norm = self
                .depth_distribution
                .sample(&mut self.rng, params.dmu, params.dsigma)
                .exp();

            self.depth_dbm = if depth_norm <= params.dlthresh {
                params.maxpathloss
            } else if depth_norm >= params.duthresh || params.duthresh == params.dlthresh {
                params.minpathloss
            } else {
                ((depth_norm - params.dlthresh) / (params.duthresh - params.dlthresh))
                    * (params.minpathloss - params.maxpathloss)
                    + params.maxpathloss
            };
            self.reset = false;
        }

        Some(10.0_f64.powf((power_dbm - self.depth_dbm) / 10.0))
    }
}

#[no_mangle]
pub extern "C" fn emane_rs_lognormal_fading_new() -> *mut LognormalFadingState {
    Box::into_raw(Box::new(LognormalFadingState::new()))
}

#[no_mangle]
pub extern "C" fn emane_rs_lognormal_fading_free(state: *mut LognormalFadingState) {
    if !state.is_null() {
        unsafe {
            drop(Box::from_raw(state));
        }
    }
}

#[no_mangle]
pub extern "C" fn emane_rs_lognormal_fading_process(
    state_ptr: *mut LognormalFadingState,
    power_dbm: f64,
    params: *const LognormalFadingParameters,
    now_microsec: u64,
) -> f64 {
    if state_ptr.is_null() || params.is_null() {
        return 0.0; // Fallback
    }

    let state = unsafe { &mut *state_ptr };
    let p = unsafe { &*params };

    state.process(power_dbm, p, now_microsec).unwrap_or(0.0)
}

#[cfg(test)]
mod lognormal_tests {
    use super::*;

    #[test]
    fn negative_depth_sigma_preserves_original_sample_and_period() {
        // The original public schema accepts signed depth sigma. These powers
        // come from its default-seeded distribution at controlled timestamps.
        let mut state = LognormalFadingState::new();
        let params = LognormalFadingParameters {
            dmu: 0.0,
            dsigma: -1.0,
            dlthresh: 0.25,
            maxpathloss: 40.0,
            duthresh: 0.75,
            minpathloss: 0.0,
            lmean: 0.001,
            lstddev: 0.001,
            counter: 1,
        };
        assert!(
            (state.process(-47.0, &params, 11_002_000).unwrap() - 2.223_241_472_745_230_4e-6).abs()
                < 1e-18
        );
        assert!(
            (state.process(-120.0, &params, 11_002_002).unwrap() - 1.114_260_243_410_600_7e-13)
                .abs()
                < 1e-24
        );
    }
}
